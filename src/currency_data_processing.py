# Importing necessary Modules
import json
import requests
from google.cloud import bigquery
from datetime import datetime
from pyspark.sql import SparkSession, functions as F
from pyspark.sql.types import StringType, NumericType, DateType
from pyspark.sql.functions import col, current_timestamp, to_date, trim, date_format, lit, when

"""## Export Data From Api"""

# Export Data From Api
spark = SparkSession.builder.appName(
    "FrankfurterAPItoSpark"
).getOrCreate()

url = "https://api.frankfurter.app/latest?from=USD"
response = requests.get(url)

# Extracting data
if response.status_code == 200:
  json_data = response.json()

  base_currency = json_data["base"]
  date = json_data["date"]
  rates_dict = json_data["rates"]

  rates_list = [
      {"base": base_currency, "date": date, "currency": curr, "rate": rate}
      for curr, rate in rates_dict.items()
  ]

  json_strings = [json.dumps(item) for item in rates_list]
  rdd = spark.sparkContext.parallelize(json_strings)
  raw_df = spark.read.json(rdd)
else:
  print("Error Connection")

# Show Results
raw_df.printSchema()
raw_df.show(5)

