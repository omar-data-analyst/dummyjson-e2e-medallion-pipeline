print("✅ Numeric Bounds Check Passed: No negative prices, stocks, or weights.")


# 3. Dynamic Check for Uncleaned Strings (Double Spaces or Empty Strings)
string_column_names = [field.name for field in df_bronze.schema.fields if isinstance(field.dataType, StringType)]
total_anomalies = 0

for col_name in string_column_names:
    anomaly_count = df_bronze.filter(
        F.col(col_name).isNull() |
        (F.col(col_name) == "") |
        F.col(col_name).rlike(r"\s{2,}")
    ).count()

    if anomaly_count > 0:
        print(f"⚠️ Warning in column '{col_name}': Found {anomaly_count} rows with empty values or double spaces.")
        total_anomalies += anomaly_count

if total_anomalies == 0:
    print("✅ String Quality Check Passed: All string columns are clean and properly trimmed.")
else:
    print(f"⚠️ Total string anomalies detected across all columns: {total_anomalies}")


# 4. Check Brand Column for Remaining Unknowns or Unmapped Values
