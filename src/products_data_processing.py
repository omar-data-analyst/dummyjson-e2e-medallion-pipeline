"""#### [1] Text Columns Cleaning Stage"""

# Trim & Clean All Strings columns

string_column_names = [field.name for field in df_bronze.schema.fields if isinstance(field.dataType, StringType)]


for column_name in string_column_names:
    df_bronze = df_bronze.withColumn(column_name, F.regexp_replace(F.col("title"), r"\s+", " "))

# Select distinct results
for column_name in string_column_names:
   anomaly_df = df_bronze.select(column_name).filter(
                F.col(column_name).isNull() |
                (F.col(column_name) == "") |
                F.col(column_name).rlike(r"\s{2,}")
   )

if anomaly_df.count() > 0:
        anomaly_df.show(5, truncate=False)
else:
        print(f"Completely clean: no violations in the column {column_name}")

# Cleaning Brand Column

