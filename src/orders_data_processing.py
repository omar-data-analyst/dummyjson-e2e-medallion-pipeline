"""## Export Data From Api"""

# Export Data From Api

spark = SparkSession.builder \
    .appName("RestaurantProductsAPItoSpark") \
    .getOrCreate()

url = 'https://dummyjson.com/carts'
response = requests.get(url)

if response.status_code == 200:
    json_data = response.json()
    products_list = json_data["carts"]

    json_strings = [json.dumps(item) for item in products_list]
    rdd = spark.sparkContext.parallelize(json_strings)
    raw_df = spark.read.json(rdd)
else:
  print('Error Connection')

# Show Results
raw_df.printSchema()
raw_df.show()

"""## **Bronze Layer**
Processing & Staging Data to ready for Silver Layer

### Unpacking internal dictionaries and lists into new columns
"""

# Unpacking internal dictionaries and lists into new columns
df_bronze = raw_df.select(
    "id",
    "userId",
    "total",
    "discountedTotal",
    "totalProducts",
    "totalQuantity",
    F.explode("products").alias("product")

    ).select(
    F.col("id").alias("cart_id"),
    "userId",
    "total",
    "discountedTotal",
    "totalProducts",
    "totalQuantity",
    
    # Unpacking Internal Columns in Product column
    F.col("product.id").alias("product_id"),
    F.col("product.title").alias("product_title"),
    F.col("product.price").alias("product_price"),
    F.col("product.quantity").alias("product_quantity"),
    F.col("product.total").alias("product_total_price"),
    F.col("product.discountPercentage").alias("product_discount_percentage"),
    F.col("product.discountedTotal").alias("product_discounted_total"),
    F.col("product.thumbnail").alias("product_thumbnail"),
)

# Add bronze_loaded_at col
df_bronze = df_bronze.withColumn('bronze_loaded_at', current_timestamp())

# Add order_id col
df_bronze = df_bronze.withColumn('order_id',
             F.concat(F.col("cart_id"),
                      F.lit("_"),
                      F.col("bronze_loaded_at").cast("string")
                      )
             )

# Show Results
df_bronze.printSchema()
df_bronze.show(10, truncate=False)

"""### Exproting Data to bronze layer"""

# 1. تحديد أسماء الجداول والمسارات
project_id = "dummyjson-e2e-pipeline"
client = bigquery.Client(project=project_id)

table_id_bronze = f"{project_id}.bronze.orders_raw"
temp_table_id = f"{project_id}.bronze.orders_raw_temp"


# Upload Data for the Temp Table
pandas_df_bronze = df_bronze.toPandas()
job_config = bigquery.LoadJobConfig(
    write_disposition="WRITE_TRUNCATE"
)
job = client.load_table_from_dataframe(pandas_df_bronze, temp_table_id, job_config=job_config)
job.result()

# Check if main table exists or not
try:
    client.get_table(table_id_bronze)
    table_exists = True
except NotFound:
    table_exists = False


if not table_exists:

    create_table_query = f"""
    CREATE TABLE `{table_id_bronze}` AS
    SELECT * FROM `{temp_table_id}`
    """

    client.query(create_table_query).result()
    print(f"Table {table_id_bronze} did not exist. Created it successfully and loaded data.")

else:
    merge_query = f"""
    MERGE `{table_id_bronze}` T
    USING `{temp_table_id}` S
    ON T.order_id = S.order_id
    WHEN MATCHED THEN
      UPDATE SET
        T.total = S.total,
        T.discountedTotal = S.discountedTotal,
        T.totalProducts = S.totalProducts,
        T.totalQuantity = S.totalQuantity,
        T.product_price = S.product_price,
        T.product_quantity = S.product_quantity,
        T.product_total_price = S.product_total_price,
        T.product_discount_percentage = S.product_discount_percentage,
        T.product_discounted_total = S.product_discounted_total
    WHEN NOT MATCHED THEN
      INSERT ROW;
    """
    client.query(merge_query).result()
    print("Successfully merged data into the existing table based on order_id.")

"""### Cleaning Stage

### Text Columns Clean Stage
"""

# Trim & Clean product_title col
df_bronze = df_bronze.withColumn('product_title', trim(F.regexp_replace(F.col('product_title'), r"\s+", " ")))

# Trim & Clean product_thumbnail col
df_bronze = df_bronze.withColumn('product_thumbnail',trim(F.regexp_replace(F.col('product_thumbnail'), r"\s+", " ")))

# Check links
df_bronze = df_bronze.withColumn(
    "product_thumbnail",
    F.when(F.col("product_thumbnail").rlike("^https?://"), F.col("product_thumbnail"))
     .otherwise(F.lit("https://via.placeholder.com/150"))
)

# Show Results
df_bronze.select("product_thumbnail").show(10, truncate=False)

# Initcap Tiproduct_title column
df_bronze = df_bronze.withColumn("product_title", F.initcap(F.col("product_title")))

# Show Results
df_bronze.select("product_title").show(10, truncate=False)

"""### Numeric Columns Clean Stage"""

# Filter id columns
df_bronze = df_bronze.filter(
    (F.col("cart_id").isNotNull()) & (F.col("cart_id") > 0) &
    (F.col("userId").isNotNull()) & (F.col("userId") > 0) &
    (F.col("product_id").isNotNull()) & (F.col("product_id") > 0) )

# Show Results
df_bronze.show(5)

# Filter Invalid Values
df_bronze = df_bronze.filter(
    (F.col('total') > 0) &
    ((F.col('discountedTotal') >= 0) | (F.col('discountedTotal').isNull())) &
    (F.col('totalProducts') > 0) &
    (F.col('totalQuantity') > 0) &
    (F.col('product_price') > 0) &
    (F.col('product_quantity') > 0) &
    (F.col('product_total_price') > 0) &
    (F.coalesce(F.col("product_discount_percentage"), F.lit(0.0)).between(0, 100)) &
    (F.col('product_discounted_total') >= 0)
)

# Show Results
df_bronze.show(5)

# Drop Duplicates on Products in same order
df_bronze = df_bronze.drop_duplicates(['cart_id', 'product_id'])

# Show Results
df_bronze.show()

# Rounding Numeric Columns
column_names = ['total','product_total_price','discountedTotal','product_price','product_quantity','product_discount_percentage','product_discounted_total']

for name in column_names:
    df_bronze = df_bronze.withColumn(name, F.round(F.col(name), 2))

# Show Results
df_bronze.select(column_names).show()

df_bronze = df_bronze.withColumn(
    "calculation_audit_status",
    F.when(
        # 1. Check whether the price × quantity does not match the total price of the product.
        F.abs((F.col("product_price") * F.col("product_quantity")) - F.col("product_total_price")) >= 0.05,
        F.lit("ERROR: Product Total Price Mismatch")
    ).when(
        # 2. Check whether the net amount after the discount does not correspond to the calculated discount percentage.
        F.abs(
            (F.col("product_total_price") * (1 - F.col("product_discount_percentage") / 100) - F.col("product_discounted_total"))
        ) >= 0.05,
        F.lit("ERROR: Discounted Total Mismatch")
    ).otherwise(
        # 3. If all accounts are consistent and correct
        F.lit("ALL_VALID")
    )
    )


# Show Results
df_bronze.select(
    "cart_id", "product_id", "product_price", "product_quantity",
    "product_total_price", "product_discount_percentage",
    "product_discounted_total", "calculation_audit_status"
).show(15, truncate=False)

